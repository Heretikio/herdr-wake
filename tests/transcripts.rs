// ------------------------------------------------------------------ Codex

fn rollout(
    home: &Path,
    day: &str,
    name_id: &str,
    meta: serde_json::Value,
    rows: &[serde_json::Value],
) -> PathBuf {
    let path = home
        .join("sessions/2026/11")
        .join(day)
        .join(format!("rollout-2026-11-{day}T09-15-02-{name_id}.jsonl"));
    let mut all = vec![json!({"type":"session_meta","payload":meta})];
    all.extend(rows.iter().cloned());
    write_lines(&path, &all);
    path
}

fn codex_user(text: &str) -> serde_json::Value {
    json!({"type":"response_item","payload":{"type":"message","role":"user",
           "content":[{"type":"input_text","text":text}]}})
}

#[test]
fn codex_sessions_get_their_name_from_the_index_or_the_first_prompt() {
    let h = tempfile::tempdir().unwrap();
    rollout(
        h.path(),
        "10",
        ID,
        json!({"id":ID,"cwd":"/work/app","source":"cli","thread_source":"user","originator":"codex-tui"}),
        &[
            codex_user("<environment_context>cwd</environment_context>"),
            codex_user("# AGENTS.md instructions for /work/app"),
            codex_user("add a health endpoint"),
        ],
    );
    rollout(
        h.path(),
        "11",
        ID2,
        json!({"id":ID2,"cwd":"/work/other","source":"cli","thread_source":"user"}),
        &[codex_user("something else")],
    );
    std::fs::write(
        h.path().join("session_index.jsonl"),
        format!(
            "{}\n{}\n",
            json!({"id":ID,"thread_name":"Old name"}),
            json!({"id":ID,"thread_name":"Health endpoint"})
        ),
    )
    .unwrap();

    let mut found = transcripts::scan_codex(h.path(), &mut Cache::new());
    found.sort_by(|a, b| a.meta.session_id.cmp(&b.meta.session_id));
    assert_eq!(found.len(), 2);
    assert_eq!(found[0].meta.session_id, ID);
    assert_eq!(found[0].meta.agent, AgentKind::Codex);
    assert_eq!(found[0].meta.title(), Some("Health endpoint"));
    assert_eq!(
        found[0].meta.prompt.as_deref(),
        Some("add a health endpoint")
    );
    assert_eq!(found[0].meta.cwd, Some(PathBuf::from("/work/app")));
    assert_eq!(found[1].meta.title(), Some("something else"));
    assert_eq!(found[1].meta.mode, None);
}

#[test]
fn codex_child_threads_and_non_interactive_runs_are_skipped() {
    let h = tempfile::tempdir().unwrap();
    let base = json!({"cwd":"/work/app","thread_source":"user"});
    let with = |extra: serde_json::Value| {
        let mut m = base.clone();
        for (k, v) in extra.as_object().unwrap() {
            m[k] = v.clone();
        }
        m
    };
    // Child thread: name with `_<child>`.
    rollout(
        h.path(),
        "10",
        &format!("{ID}_{ID2}"),
        with(json!({"id":ID,"source":"cli"})),
        &[codex_user("child work")],
    );
    // Sub-agent by source object.
    rollout(
        h.path(),
        "11",
        "0b5a2c1e-1111-4222-8333-000000000002",
        with(json!({"source":{"subagent":"review"}})),
        &[codex_user("review")],
    );
    // codex exec.
    rollout(
        h.path(),
        "12",
        "0b5a2c1e-1111-4222-8333-000000000003",
        with(json!({"source":"exec"})),
        &[codex_user("one shot")],
    );
    // A non-user thread source.
    rollout(
        h.path(),
        "13",
        "0b5a2c1e-1111-4222-8333-000000000004",
        with(json!({"source":"cli","thread_source":"guardian"})),
        &[codex_user("guardian")],
    );
    // A conversation-less rollout.
    rollout(
        h.path(),
        "14",
        "0b5a2c1e-1111-4222-8333-000000000005",
        with(json!({"source":"cli"})),
        &[],
    );
    // A compressed rollout is not read.
    let z = h.path().join("sessions/2026/11/15/rollout-2026-11-15T09-15-02-0b5a2c1e-1111-4222-8333-000000000006.jsonl.zst");
    std::fs::create_dir_all(z.parent().unwrap()).unwrap();
    std::fs::write(&z, "zst").unwrap();

    assert!(transcripts::scan_codex(h.path(), &mut Cache::new()).is_empty());
}

#[test]
fn meta_of_reads_one_file_and_ignores_pi_and_opencode() {
    let c = tempfile::tempdir().unwrap();
    let f = claude_file(c.path(), "p", ID);
    write_lines(&f, &[user("hello world")]);
    let mut cache = Cache::new();
    let got = transcripts::meta_of(AgentKind::Claude, &f, &mut cache).unwrap();
    assert_eq!(got.meta.title(), Some("hello world"));
    assert!(transcripts::meta_of(AgentKind::Pi, &f, &mut cache).is_none());
    assert!(transcripts::meta_of(AgentKind::OpenCode, &f, &mut cache).is_none());
    assert!(
        transcripts::meta_of(AgentKind::Claude, &c.path().join("nope.jsonl"), &mut cache).is_none()
    );
    let _: BTreeMap<String, String> = BTreeMap::new();
}
