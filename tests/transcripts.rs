//! Reading Claude Code and Codex transcripts for `herdr-wake resurrect`:
//! titles, flags, what is skipped, the bounded reads and the cache.

use std::collections::BTreeMap;
use std::io::Write;
use std::os::unix::fs::PermissionsExt;
use std::path::{Path, PathBuf};

use herdr_wake::record::AgentKind;
use herdr_wake::transcripts::{self, Cache};
use serde_json::json;

const ID: &str = "0b5a2c1e-1111-4222-8333-444455556666";
const ID2: &str = "0b5a2c1e-1111-4222-8333-777788889999";

fn write_lines(path: &Path, rows: &[serde_json::Value]) {
    std::fs::create_dir_all(path.parent().unwrap()).unwrap();
    let mut f = std::fs::File::create(path).unwrap();
    for r in rows {
        writeln!(f, "{r}").unwrap();
    }
}

fn user(text: &str) -> serde_json::Value {
    json!({"type":"user","cwd":"/work/app","entrypoint":"cli","isSidechain":false,
           "message":{"role":"user","content":text}})
}

fn claude_file(config: &Path, project: &str, id: &str) -> PathBuf {
    config
        .join("projects")
        .join(project)
        .join(format!("{id}.jsonl"))
}

fn scan(config: &Path) -> Vec<transcripts::Found> {
    transcripts::scan_claude(config, &mut Cache::new())
}

#[test]
fn claude_title_order_is_custom_then_ai_then_first_real_prompt() {
    let c = tempfile::tempdir().unwrap();
    let f = claude_file(c.path(), "-work-app", ID);
    write_lines(
        &f,
        &[
            json!({"type":"permission-mode","permissionMode":"plan"}),
            json!({"type":"user","isMeta":true,"cwd":"/work/app","message":{"role":"user","content":"meta text"}}),
            user("<system-reminder>reminder</system-reminder>"),
            user("<command-name>/clear</command-name>"),
            user("Caveat: The messages below were generated by the user while running local commands."),
            json!({"type":"user","cwd":"/work/app","isSidechain":false,
                   "message":{"role":"user","content":[{"type":"tool_result","content":"x"}]}}),
            user("  fix the\nlogin   bug  "),
            json!({"type":"ai-title","aiTitle":"Login bug fix"}),
        ],
    );
    let found = scan(c.path());
    assert_eq!(found.len(), 1);
    let m = &found[0].meta;
    assert_eq!(m.session_id, ID);
    assert_eq!(m.cwd, Some(PathBuf::from("/work/app")));
    assert_eq!(m.mode.as_deref(), Some("plan"));
    assert_eq!(m.prompt.as_deref(), Some("fix the login bug"));
    assert_eq!(m.title(), Some("Login bug fix"));

    // A custom title (later in the file) beats the AI title.
    let mut text = std::fs::read_to_string(&f).unwrap();
    text.push_str(&json!({"type":"custom-title","customTitle":"My name"}).to_string());
    text.push('\n');
    std::fs::write(&f, text).unwrap();
    assert_eq!(scan(c.path())[0].meta.title(), Some("My name"));

    // Without either, the first real prompt.
    write_lines(
        &f,
        &[
            user("<system-reminder>x</system-reminder>"),
            user("hello there"),
        ],
    );
    assert_eq!(scan(c.path())[0].meta.title(), Some("hello there"));
}

