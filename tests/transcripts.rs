#[test]
fn the_cache_skips_unchanged_files_and_rereads_changed_ones() {
    let c = tempfile::tempdir().unwrap();
    let f = claude_file(c.path(), "p", ID);
    write_lines(&f, &[user("original")]);
    let state = tempfile::tempdir().unwrap();
    let cache_file = state.path().join("transcripts.json");

    let mut cache = Cache::load(&cache_file);
    assert_eq!(
        transcripts::scan_claude(c.path(), &mut cache)[0]
            .meta
            .title(),
        Some("original")
    );
    cache.save(&cache_file).unwrap();
    assert!(cache_file.is_file());
    assert_eq!(
        std::fs::metadata(&cache_file).unwrap().permissions().mode() & 0o777,
        0o600
    );

    // Unreadable but unchanged (same size and mtime): answered from the cache.
    std::fs::set_permissions(&f, std::fs::Permissions::from_mode(0o000)).unwrap();
    let mut cache = Cache::load(&cache_file);
    let again = transcripts::scan_claude(c.path(), &mut cache);
    std::fs::set_permissions(&f, std::fs::Permissions::from_mode(0o644)).unwrap();
    assert_eq!(again.len(), 1);
    assert_eq!(again[0].meta.title(), Some("original"));

    // A changed file is read again.
    write_lines(&f, &[user("changed words here")]);
    let mut cache = Cache::load(&cache_file);
    assert_eq!(
        transcripts::scan_claude(c.path(), &mut cache)[0]
            .meta
            .title(),
        Some("changed words here")
    );
}

#[test]
fn the_cache_is_rebuilt_when_its_version_changes_and_keeps_only_seen_files() {
    let c = tempfile::tempdir().unwrap();
    let f = claude_file(c.path(), "p", ID);
    write_lines(&f, &[user("hello")]);
    let state = tempfile::tempdir().unwrap();
    let cache_file = state.path().join("transcripts.json");

    // A file of another version is ignored.
    std::fs::write(
        &cache_file,
        r#"{"version":0,"files":{"/gone":{"size":1,"mtime_ms":1,"meta":null}}}"#,
    )
    .unwrap();
    let mut cache = Cache::load(&cache_file);
    transcripts::scan_claude(c.path(), &mut cache);
    cache.save(&cache_file).unwrap();
    let text = std::fs::read_to_string(&cache_file).unwrap();
    assert!(text.contains(&format!("\"version\":{}", transcripts::CACHE_VERSION)));
    assert!(!text.contains("/gone"));

    // A file that vanished leaves the cache at the next save.
    std::fs::remove_file(&f).unwrap();
    let mut cache = Cache::load(&cache_file);
    assert!(transcripts::scan_claude(c.path(), &mut cache).is_empty());
    cache.save(&cache_file).unwrap();
    assert!(!std::fs::read_to_string(&cache_file).unwrap().contains(ID));
}

